import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'assets/data/kanda');
const outFile = path.join(root, 'src/generated/searchIndex.ts');

function stripHtml(html) {
  return html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const kandas = fs.readdirSync(dataDir).filter((name) =>
  fs.statSync(path.join(dataDir, name)).isDirectory()
);

const documents = [];

for (const kanda of kandas) {
  const proseDir = path.join(dataDir, kanda, 'prose/chapter');
  if (!fs.existsSync(proseDir)) continue;

  const files = fs.readdirSync(proseDir).filter((f) => f.endsWith('.json'));
  for (const file of files) {
    const sargaNum = file.replace('.json', '');
    const raw = JSON.parse(fs.readFileSync(path.join(proseDir, file), 'utf8'));
    const body = (raw.content ?? [])
      .map((block) => stripHtml(block.text ?? ''))
      .filter(Boolean)
      .join(' ');

    documents.push({
      id: `${kanda}-${sargaNum}`,
      kanda,
      sarga: sargaNum,
      title: raw.title ?? '',
      overview: stripHtml(raw.overview ?? ''),
      body,
    });
  }
}

documents.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));

const lines = [
  '// Auto-generated by scripts/generate-search-index.mjs — do not edit manually',
  "import type { TKanda } from '@/types/content';",
  '',
  'export type SearchDocument = {',
  '  id: string;',
  '  kanda: TKanda;',
  '  sarga: string;',
  '  title: string;',
  '  overview: string;',
  '  body: string;',
  '};',
  '',
  'export const searchDocuments: SearchDocument[] = [',
  ...documents.map((doc) => {
    const json = JSON.stringify(doc);
    return `  ${json},`;
  }),
  '];',
  '',
];

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`Generated ${documents.length} search documents → ${outFile}`);
