import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import MiniSearch from 'minisearch';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'assets/data/kanda');
const engineFile = path.join(root, 'assets/search/engine.json');
const typesFile = path.join(root, 'src/generated/searchIndex.ts');

const BODY_INDEX_LIMIT = 2800;
const OVERVIEW_INDEX_LIMIT = 600;

const SEARCH_FIELDS = ['title', 'overview', 'body'];
const STORE_FIELDS = ['kanda', 'sarga', 'title', 'overview', 'body'];

function stripHtml(html) {
  return html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function clip(text, limit) {
  if (text.length <= limit) return text;
  return `${text.slice(0, limit).trim()}…`;
}

const kandas = fs.readdirSync(dataDir).filter((name) =>
  fs.statSync(path.join(dataDir, name)).isDirectory()
);

const documents = [];

for (const kanda of kandas) {
  const proseDir = path.join(dataDir, kanda, 'prose/chapter');
  if (!fs.existsSync(proseDir)) continue;

  const files = fs.readdirSync(proseDir).filter((f) => f.endsWith('.json'));
  for (const file of files) {
    const sargaNum = file.replace('.json', '');
    const raw = JSON.parse(fs.readFileSync(path.join(proseDir, file), 'utf8'));
    const body = clip(
      (raw.content ?? [])
        .map((block) => stripHtml(block.text ?? ''))
        .filter(Boolean)
        .join(' '),
      BODY_INDEX_LIMIT
    );

    documents.push({
      id: `${kanda}-${sargaNum}`,
      kanda,
      sarga: sargaNum,
      title: raw.title ?? '',
      overview: clip(stripHtml(raw.overview ?? ''), OVERVIEW_INDEX_LIMIT),
      body,
    });
  }
}

documents.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));

const engine = new MiniSearch({
  fields: SEARCH_FIELDS,
  storeFields: STORE_FIELDS,
  searchOptions: {
    boost: { title: 5, overview: 2, body: 1 },
    fuzzy: 0.12,
    prefix: true,
  },
});

engine.addAll(documents);

fs.mkdirSync(path.dirname(engineFile), { recursive: true });
fs.writeFileSync(engineFile, JSON.stringify(engine));

const typesSource = `// Auto-generated by scripts/generate-search-index.mjs — do not edit manually
import type { TKanda } from '@/types/content';

export type SearchDocument = {
  id: string;
  kanda: TKanda;
  sarga: string;
  title: string;
  overview: string;
  body: string;
};

export const SEARCH_DOCUMENT_COUNT = ${documents.length};
`;

fs.mkdirSync(path.dirname(typesFile), { recursive: true });
fs.writeFileSync(typesFile, typesSource);

const engineKb = Math.round(fs.statSync(engineFile).size / 1024);
console.log(`Generated ${documents.length} search documents`);
console.log(`  → ${path.relative(root, engineFile)} (${engineKb} KB)`);
console.log(`  → ${path.relative(root, typesFile)}`);
