import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'assets/data/kanda');
const outFile = path.join(root, 'src/generated/sargaContentMap.ts');

const kandas = fs.readdirSync(dataDir).filter((name) =>
  fs.statSync(path.join(dataDir, name)).isDirectory()
);

const entries = [];

for (const kanda of kandas) {
  const proseDir = path.join(dataDir, kanda, 'prose/chapter');
  if (!fs.existsSync(proseDir)) continue;

  const files = fs.readdirSync(proseDir).filter((f) => f.endsWith('.json'));
  for (const file of files) {
    const sargaNum = file.replace('.json', '');
    const key = `${kanda}-${sargaNum}`;
    const relPath = `../../assets/data/kanda/${kanda}/prose/chapter/${file}`;
    entries.push({ key, relPath });
  }
}

entries.sort((a, b) => a.key.localeCompare(b.key, undefined, { numeric: true }));

const lines = [
  '// Auto-generated by scripts/generate-content-map.mjs — do not edit manually',
  "import type { Sarga } from '@/types/content';",
  '',
  'export const sargaContentMap: Record<string, Sarga> = {',
  ...entries.map(({ key, relPath }) => `  '${key}': require('${relPath}'),`),
  '};',
  '',
];

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`Generated ${entries.length} sarga entries → ${outFile}`);
